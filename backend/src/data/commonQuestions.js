/**
 * 根据问题文本 + 类别，匹配最近的常见问题档案
 * 返回 { profileKey, ...profile } 或 null
 */
function matchQuestionProfile(question, category) {
  const categoryProfiles = COMMON_QUESTION_PROFILES[category]
  if (!categoryProfiles) return null

  for (const [profileKey, profile] of Object.entries(categoryProfiles)) {
    if (profile.keywords.some(kw => question.includes(kw))) {
      return { profileKey, ...profile }
    }
  }
  return null
}

/**
 * 随机取一条追问问候语
 */
function getFollowUpGreeting(profile) {
  if (!profile?.followUpGreetings?.length) return null
  const idx = Math.floor(Math.random() * profile.followUpGreetings.length)
  return profile.followUpGreetings[idx]
}

/**
 * 获取推荐追问问题
 */
function getSuggestedFollowUps(profile) {
  return profile?.suggestedFollowUps || []
}

/** 结果页追问引导（问候 + chips） */
function buildFollowUpHints(question, category) {
  const profile = matchQuestionProfile(question, category)
  if (!profile) return { greeting: null, suggestions: [] }
  return {
    greeting: getFollowUpGreeting(profile),
    suggestions: getSuggestedFollowUps(profile),
    profileKey: profile.profileKey,
    talkingPoints: profile.talkingPoints,
  }
}

/** 给 AI prompt 的解读要点（参考，不照搬） */
function formatProfileHintForPrompt(profile) {
  if (!profile?.talkingPoints?.length) return ''
  return `\n这类问题的解读要点（参考，不要照搬）：\n${profile.talkingPoints.map((p) => `- ${p}`).join('\n')}`
}


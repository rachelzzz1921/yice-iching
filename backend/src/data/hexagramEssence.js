function getEssence(guaId) {
  return HEXAGRAM_ESSENCE[guaId] || null
}

function getSignal(guaId, category) {
  const entry = HEXAGRAM_ESSENCE[guaId]
  if (!entry) return null
  return entry.signal[category] || null
}

function buildEssenceContext(benGuaId, bianGuaId, category) {
  const ben = HEXAGRAM_ESSENCE[benGuaId]
  const bian = bianGuaId ? HEXAGRAM_ESSENCE[bianGuaId] : null

  if (!ben) return ''

  let ctx = `本卦【${ben.name}】卦性：${ben.essence}`
  if (ben.signal[category]) {
    ctx += `\n${category}方向信号：${ben.signal[category]}`
  }

  if (bian) {
    ctx += `\n变卦【${bian.name}】卦性：${bian.essence}`
    if (bian.signal[category]) {
      ctx += `\n变卦${category}信号：${bian.signal[category]}`
    }
  }

  return ctx
}

module.exports = { HEXAGRAM_ESSENCE, getEssence, getSignal, buildEssenceContext }

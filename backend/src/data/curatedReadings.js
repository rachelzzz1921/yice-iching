function getSampleReadings(category, count = 2) {
  const pool = CURATED_READINGS.filter(r => r.category === category)
  const shuffled = [...pool].sort(() => Math.random() - 0.5)
  return shuffled.slice(0, count)
}

/**
 * 组装给AI的范例上下文（注入prompt）
 * 精确命中：直接给AI这个范例作为改写基础
 * 未命中：给同类别的随机范例作为风格参考
 */
function buildCuratedContext(guaId, bianGuaId, category) {
  const exact = findExactReading(guaId, bianGuaId, category)

  if (exact) {
    return `【精选范例：与此次卦象高度匹配，在此基础上结合实际问题改写】
本卦：${exact.guaId} 变卦：${exact.bianGuaId || '无'} 类别：${exact.category}
问题类型：${exact.questionType}
一句话定性示例：「${exact.headline}」

维度范例（感受密度和语气，结合用户实际问题改写）：
时机/缘分：${exact.sections.timing}
阻力/障碍：${exact.sections.obstacle}
建议：${exact.sections.advice}
走向/结果：${exact.sections.outcome}
断语：${exact.sections.verdict}`
  }

  // 未精确命中，给风格参考
  const samples = getSampleReadings(category, 1)
  if (!samples.length) return ''

  const sample = samples[0]
  return `【风格参考范例：感受此风格的密度和语气，不要照搬内容】
一句话定性示例：「${sample.headline}」
断语示例：「${sample.sections.verdict}」
整体风格：直接、具体、有时间节点、有可操作的建议、不说废话。`
}


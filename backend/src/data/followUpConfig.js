/**
 * 识别追问意图
 */
function detectIntent(userMessage) {
  for (const [intentKey, intent] of Object.entries(FOLLOWUP_INTENTS)) {
    if (intent.patterns.some(p => userMessage.includes(p))) {
      return { intentKey, ...intent }
    }
  }
  return { intentKey: 'general', skill: null, description: '通用追问' }
}

/**
 * 获取对应技能框架
 */
function getSkill(skillName) {
  return FOLLOWUP_SKILLS[skillName] || null
}

/**
 * 从案例库里随机取N条对话示例（few-shot用）
 */
function getExamples(category, count = 2) {
  const pool = FOLLOWUP_EXAMPLES[category] || FOLLOWUP_EXAMPLES.career
  const shuffled = [...pool].sort(() => Math.random() - 0.5)
  return shuffled.slice(0, count)
}

/**
 * 随机取一条大师语料（按类型）
 */
function getMasterPhrase(type) {
  const pool = MASTER_PHRASES[type]
  if (!pool?.length) return ''
  return pool[Math.floor(Math.random() * pool.length)]
}

/**
 * 组装完整的追问system prompt
 * 包含：人格设定 + 意图技能 + few-shot案例
 */
function buildFollowUpPrompt({ category, userMessage }) {
  const systemBase = buildFollowUpSystem(category)
  const intent = detectIntent(userMessage)
  const skill = intent.skill ? getSkill(intent.skill) : null
  const examples = getExamples(category, 2)

  let skillSection = ''
  if (skill) {
    skillSection = `
【这次追问的类型：${skill.name}】
回答框架参考：
${skill.framework}

好的回答示例：
${skill.example}
`
  }

  const exampleSection = examples.map(ex =>
    `用户：「${ex.user}」\n大师：「${ex.master}」`
  ).join('\n\n')

  return `${systemBase}

${skillSection}

【语感参考，感受这个风格，不要照抄】
${exampleSection}
`
}


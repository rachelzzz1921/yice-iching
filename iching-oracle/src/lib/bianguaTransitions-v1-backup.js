/**
 * 获取变卦转化信息
 * @param {number} fromId 本卦ID
 * @param {number} toId   变卦ID
 * @param {string} category 问事类别
 */
function getTransition(fromId, toId, category) {
  const key = `${fromId}-${toId}`
  const data = BIANUA_TRANSITIONS[key]
  if (!data) return null

  return {
    ...data,
    categorySignal: data.signal[category] || data.signal.fate || data.signal.career,
  }
}

/**
 * 组装给AI的变卦上下文字符串（注入prompt）
 */
function buildTransitionContext(benGuaId, bianGuaId, category) {
  if (!bianGuaId) return '此卦无变卦，局面相对稳定，参考本卦卦性即可。'

  const data = getTransition(benGuaId, bianGuaId, category)
  if (!data) {
    return `本卦变为${bianGuaId}卦，具体转化需结合卦性判断。`
  }

  return `变卦转化：【${data.fromName}】→【${data.toName}】
转化性质：${data.nature === 'improvement' ? '好转' : data.nature === 'deterioration' ? '转差' : data.nature === 'transformation' ? '质变' : data.nature === 'stabilization' ? '稳定' : '警示'}
转化象意：${data.transition}
${category}走向信号：${data.categorySignal}
断语方向：${data.verdict}
AI提示：${data.aiHint}`
}

/**
 * 获取转化性质的中文标签
 */
function getNatureLabel(nature) {
  const map = {
    improvement: '向好转化',
    deterioration: '转差警示',
    transformation: '质的转变',
    stabilization: '趋于稳定',
    warning: '有隐患需注意',
  }
  return map[nature] || '转化中'
}


/**
 * 识别用户追问的核心意图
 * 优先级：情绪出口 > 其他（情绪状态下不适合给理性分析）
 */
function detectIntent(userMessage) {
  // 先检查情绪信号（最高优先级）
  const emotionalIntent = INTENT_DEFINITIONS.emotional
  if (emotionalIntent.patterns.some(p => userMessage.includes(p))) {
    return {
      intentKey: 'emotional',
      ...emotionalIntent,
    }
  }

  // 其他意图按顺序匹配
  for (const [intentKey, intent] of Object.entries(INTENT_DEFINITIONS)) {
    if (intentKey === 'emotional') continue
    if (intent.patterns.some(p => userMessage.includes(p))) {
      return { intentKey, ...intent }
    }
  }

  // 未命中：返回通用意图
  return {
    intentKey: 'general',
    label: '通用追问',
    coreQuestion: '用户在追问具体细节',
    traps: ['不要废话', '直接回答', '不超过100字'],
    answerStructure: ['直接回答问题', '给出卦象依据', '给出可操作的建议'],
    maxLength: 100,
  }
}

/**
 * 将意图定义转为prompt注入字符串
 */
function intentToPromptHint(intent) {
  if (!intent || intent.intentKey === 'general') return ''

  const trapsText = intent.traps?.map(t => `- ${t}`).join('\n') || ''
  const structureText = intent.answerStructure?.map((s, i) => `${i + 1}. ${s}`).join('\n') || ''

  return `【本次追问意图：${intent.label}】
用户真正想知道的：${intent.coreQuestion}

回答时避免：
${trapsText}

回答结构：
${structureText}

字数控制：${intent.maxLength}字以内`
}


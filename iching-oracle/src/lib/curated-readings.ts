export function curatedKey(input: CuratedLookup): string {
  return `${input.benName}|${input.bianName ?? ""}|${input.category}|${input.changingLine}`;
}

/** 精确匹配；有变卦时若无精确键，回退 ben||category|动爻 */
export function resolveCurated(input: CuratedLookup): CuratedSections | null {
  const exact = CURATED_READINGS[curatedKey(input)];
  if (exact) return exact;
  if (input.bianName) {
    const loose = CURATED_READINGS[`${input.benName}||${input.category}|${input.changingLine}`];
    if (loose) return loose;
  }
  return null;
}
